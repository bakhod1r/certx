func (a *Adapter) Reload(ctx context.Context, inst webserver.Installation) (string, error) {
	if inst.Binary == "" {
		return "", errors.New("apache binary not found")
	}
	switch filepath.Base(inst.Binary) {
	case "apache2ctl", "apachectl":
		return execx.Run(ctx, inst.Binary, "graceful")
	default:
		args := []string{"-k", "graceful"}
		if inst.ConfigPath != "" && filepath.Base(inst.Binary) == "httpd" {
			args = append(args, "-f", inst.ConfigPath)
		}
		return execx.Run(ctx, inst.Binary, args...)
	}
}

func (a *Adapter) EditTLS(src []byte, vh webserver.VirtualHost, c webserver.CertPaths, o webserver.TLSOptions) (*webserver.Patch, error) {
	n, err := findVirtualHost(src, vh.Line)
	if err != nil {
		return nil, err
	}
	lines := splitLines(src)
	if vh.TLS() {
		return &webserver.Patch{After: editSSLDirectives(lines, n, c)}, nil
	}
	return a.addSSLVirtualHost(lines, n, vh, c, o)
}

func (a *Adapter) EditChallenge(src []byte, vh webserver.VirtualHost, root string) (*webserver.Patch, error) {
	n, err := findVirtualHost(src, vh.Line)
	if err != nil {
		return nil, err
	}
	lines := splitLines(src)
	dir := filepath.Join(root, ".well-known", "acme-challenge") + "/"
	ind := indentOf(lines, n)
	// Inserted first in the vhost: ProxyPass rules match in order, so the
	// exclusion must precede any "ProxyPass /".
	block := []string{
		ind + "# " + webserver.ChallengeMarker,
		ind + "<IfModule mod_proxy.c>",
		ind + "    ProxyPass /.well-known/acme-challenge/ !",
		ind + "</IfModule>",
		ind + fmt.Sprintf("Alias /.well-known/acme-challenge/ %q", dir),
		ind + fmt.Sprintf("<Directory %q>", dir),
		ind + "    Require all granted",
		ind + "</Directory>",
	}
	return &webserver.Patch{After: join(insertLines(lines, n.Line, block))}, nil
}

// editSSLDirectives points an existing SSL vhost at the new certificate.
func editSSLDirectives(lines []string, n *conftree.Node, c webserver.CertPaths) []byte {
	ind := indentOf(lines, n)
	certLine, keySeen := 0, false
	var walk func([]*conftree.Node)
	walk = func(ds []*conftree.Node) {
		for _, d := range ds {
			if d.Block {
				walk(d.Children)
				continue
			}
			i := d.Line - 1
			lead := leading(lines[i])
			switch {
			case d.Is("SSLCertificateFile"):
				lines[i] = lead + "SSLCertificateFile " + quote(c.Cert)
				certLine = d.Line
			case d.Is("SSLCertificateKeyFile"):
				lines[i] = lead + "SSLCertificateKeyFile " + quote(c.Key)
				keySeen = true
			case d.Is("SSLCertificateChainFile"):
				// The new certificate file already contains the chain.
				lines[i] = lead + "# " + strings.TrimSpace(lines[i])
			}
		}
	}
	walk(n.Children)
	var add []string
	if certLine == 0 {
		add = append(add, ind+"SSLCertificateFile "+quote(c.Cert))
	}
	if !keySeen {
		add = append(add, ind+"SSLCertificateKeyFile "+quote(c.Key))
	}
	if len(add) > 0 {
		at := n.EndLine - 1
		if certLine != 0 {
			at = certLine
		}
		lines = insertLines(lines, at, add)
	}
	return join(lines)
}

// addSSLVirtualHost copies a plain HTTP vhost into a new *-certx-ssl.conf
// file listening on 443, preserving its proxy, alias and directory rules.
func (a *Adapter) addSSLVirtualHost(lines []string, n *conftree.Node, vh webserver.VirtualHost, c webserver.CertPaths, o webserver.TLSOptions) (*webserver.Patch, error) {
	real := webserver.RealPath(vh.File)
	dir := filepath.Dir(real)
	name := strings.TrimSuffix(filepath.Base(real), ".conf") + "-certx-ssl.conf"
	target := filepath.Join(dir, name)
	if _, err := os.Lstat(target); err == nil {
		return nil, fmt.Errorf("%s already exists", target)
	}

	addr := "*"
	if len(vh.Listen) > 0 && vh.Listen[0].Addr != "" {
		addr = vh.Listen[0].Addr
	}
	ind := indentOf(lines, n)
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by CertX from %s:%d\n<IfModule mod_ssl.c>\n<VirtualHost %s:443>\n", vh.File, vh.Line, addr)
	for _, l := range dropHTTPSRedirects(lines[n.Line : n.EndLine-1]) {
		b.WriteString(l + "\n")
	}
	fmt.Fprintf(&b, "\n%sSSLEngine on\n%sSSLCertificateFile %s\n%sSSLCertificateKeyFile %s\n</VirtualHost>\n</IfModule>\n",
		ind, ind, quote(c.Cert), ind, quote(c.Key))

	p := &webserver.Patch{Extra: []webserver.FileEdit{{Server: webserver.KindApache, Path: target, After: []byte(b.String()), Mode: 0o644}}}
	if filepath.Base(dir) == "sites-available" {
		enabled := filepath.Join(filepath.Dir(dir), "sites-enabled")
		if fi, err := os.Stat(enabled); err == nil && fi.IsDir() {
			p.Extra = append(p.Extra, webserver.FileEdit{
				Server: webserver.KindApache, Path: filepath.Join(enabled, name), Symlink: "../sites-available/" + name,
			})
		}
		if mods := modsEnabled(dir); mods != "" {
			if _, err := os.Stat(filepath.Join(mods, "ssl.load")); err != nil {
				p.Notes = append(p.Notes, "mod_ssl is not enabled: run `a2enmod ssl` before deploying")
			}
		}
	}
	if o.Redirect && !vh.RedirectsToHTTPS {
		// mod_rewrite runs before mod_proxy and mod_alias, so this also
		// works for vhosts with "ProxyPass /", where Redirect would not.
		redirect := []string{
			ind + "# " + webserver.ManagedMarker,
			ind + "RewriteEngine on",
			ind + `RewriteCond %{REQUEST_URI} !^/\.well-known/acme-challenge/`,
			ind + "RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [END,NE,R=permanent]",
		}
		p.After = join(insertLines(lines, n.EndLine-1, redirect))
		if mods := modsEnabled(dir); mods != "" {
			if _, err := os.Stat(filepath.Join(mods, "rewrite.load")); err != nil {
				p.Notes = append(p.Notes, "mod_rewrite is not enabled: run `a2enmod rewrite` before deploying")
			}
		}
	}
	return p, nil
}

// modsEnabled returns the Debian mods-enabled directory next to a
// sites-available directory, or "".
func modsEnabled(sitesDir string) string {
	if filepath.Base(sitesDir) != "sites-available" {
		return ""
	}
	mods := filepath.Join(filepath.Dir(sitesDir), "mods-enabled")
	if fi, err := os.Stat(mods); err == nil && fi.IsDir() {
		return mods
	}
	return ""
}

// dropHTTPSRedirects removes redirects to https (and their RewriteCond
// lines) so the copied SSL vhost does not redirect to itself.
func dropHTTPSRedirects(lines []string) []string {
	var out, conds []string
	for _, l := range lines {
		f := splitArgs(strings.TrimSpace(l))
		name := ""
		if len(f) > 0 {
			name = strings.ToLower(f[0])
		}
		switch {
		case name == "rewritecond":
			conds = append(conds, l)
			continue
		case (name == "rewriterule" || strings.HasPrefix(name, "redirect")) && strings.Contains(l, "https://"):
			conds = nil
			continue
		}
		out = append(out, conds...)
		conds = nil
		out = append(out, l)
	}
	return append(out, conds...)
}

func findVirtualHost(src []byte, line int) (*conftree.Node, error) {
	p := newParser("/", true)
	p.noInclude = true
	ls := logicalLines(string(src))
	i := 0
	nodes, err := p.parseSection("", ls, &i, "")
	if err != nil {
		return nil, err
	}
	var found *conftree.Node
	var walk func([]*conftree.Node)
	walk = func(ns []*conftree.Node) {
		for _, n := range ns {
			if found != nil || !n.Block {
				continue
			}
			if n.Is("VirtualHost") && n.Line == line {
				found = n
				return
			}
			walk(n.Children)
		}
	}
	walk(nodes)
	if found == nil {
		return nil, fmt.Errorf("<VirtualHost> at line %d not found (file changed since scan?)", line)
	}
	return found, nil
}

// splitLines splits into lines without terminators; join restores them.
func splitLines(src []byte) []string {
	s := strings.TrimSuffix(string(src), "\n")
	return strings.Split(s, "\n")
}

func join(lines []string) []byte {
	return []byte(strings.Join(lines, "\n") + "\n")
}

// insertLines inserts add after the first `at` lines.
func insertLines(lines []string, at int, add []string) []string {
	out := append([]string(nil), lines[:at]...)
	out = append(out, add...)
	return append(out, lines[at:]...)
}

func leading(s string) string {
	return s[:len(s)-len(strings.TrimLeft(s, " \t"))]
}

// indentOf returns the indentation of the first directive inside n.
func indentOf(lines []string, n *conftree.Node) string {
	for i := n.Line; i < n.EndLine-1 && i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) != "" {
			return leading(lines[i])
		}
	}
	return leading(lines[n.Line-1]) + "    "
}

func quote(s string) string {
	if strings.ContainsAny(s, " \t\"") {
		return fmt.Sprintf("%q", s)
	}
	return s
}
